/**
 * Wrap client.source.js into the module-registration envelope the DSH web shell
 * serves from `/plugins/<package>/client.js`.
 *
 * Two things here are load-bearing, both learned the hard way from Desktop boot
 * failures ("web boot: 1 entry did not activate" / "dsh-think-zh: import failed"):
 *
 * 1. THE GLOBAL IS `window.__ModuleLoader__` — DOUBLE underscore. All 57 shipped
 *    client bundles register exactly this way. A near-miss spelling
 *    (`_ModuleLoader__`) is an undeclared identifier, so the bundle throws
 *    `ReferenceError`, nothing registers, and the shell reports the useless
 *    message "import failed (see console for the import error)".
 *
 * 2. REGISTRATION MUST BE SYNCHRONOUS AND TOP-LEVEL. The shell loads a combo and
 *    then immediately checks that every entry in it registered. A deferred
 *    registration (polling for a loader that was never missing) lands one tick
 *    too late and is reported as
 *    `loaded without registering "<id>" via __ModuleLoader__.load`.
 *
 * Both are pinned by test/registration.test.mjs and scripts/smoke-client.mjs.
 * The bundle is plain ES2022 — no bundler — because the platform module table
 * already provides react, react-dom/client and dsh-client-ui-primitives.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const sourcePath = path.join(root, 'client.source.js');
const outPath = path.join(root, 'lib', 'client.js');

const IMPORT_LINES = [
  "import React from 'react';",
  "import { createRoot } from 'react-dom/client';",
];

/**
 * Turn the source's static imports into `require` bindings inside the factory.
 * Handles both `import X from 'pkg'` and `import { A, B } from 'pkg'`; a binding
 * named twice is emitted once.
 */
function collectImports(source) {
  const lines = [];
  const bindings = [];
  const add = (line) => {
    if (!bindings.includes(line)) bindings.push(line);
  };
  /* `import { A, B } from 'pkg'` -> read those names off the module. */
  const named = /^import\s*\{([^}]+)\}\s*from\s*'([^']+)';[ \t]*$/gm;
  let match;
  while ((match = named.exec(source)) !== null) {
    lines.push(match[0]);
    for (const name of match[1].split(',').map((v) => v.trim()).filter(Boolean)) {
      add(`\t\tvar ${name} = require(${JSON.stringify(match[2])}).${name};`);
    }
  }
  /* `import X from 'pkg'` -> X IS the module namespace object. Reading `.X` off it
     is undefined (that is how `React.useMemo` became "cannot read properties of
     undefined"), so the whole module is bound. */
  const def = /^import\s+([A-Za-z_$][\w$]*)\s+from\s*'([^']+)';[ \t]*$/gm;
  while ((match = def.exec(source)) !== null) {
    lines.push(match[0]);
    add(`\t\tvar ${match[1]} = require(${JSON.stringify(match[2])});`);
  }
  return { lines, bindings };
}

const source = await readFile(sourcePath, 'utf8');
const packageJson = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));

const missing = IMPORT_LINES.filter((line) => !source.includes(line));
if (missing.length > 0) throw new Error(`client.source.js lost its platform imports:\n${missing.join('\n')}`);

const platform = collectImports(source);

const body = source
  .split('\n')
  .filter((line) => !IMPORT_LINES.includes(line.trim()) && !platform.lines.includes(line.trim()))
  .join('\n')
  .replace(/^\n+/, '')
  // The factory has no module scope for ESM syntax; the wrapper re-exports the
  // declarative names afterwards.
  .replace(/^export (function|const|let|class) /gm, '$1 ')
  .split('\n')
  .map((line) => (line === '' ? '' : `\t\t${line}`))
  .join('\n');

const exported = [
  ...source.matchAll(/^export function (\w+)/gm),
  ...source.matchAll(/^export const (\w+)/gm),
].map((match) => match[1]);
if (exported.length === 0) throw new Error('client.source.js exports nothing');

const bundle = `/* ${packageJson.name} v${packageJson.version} — generated by scripts/build-client.mjs; edit client.source.js instead. */
window.__ModuleLoader__.load({
	id: ${JSON.stringify(packageJson.name)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' });
${platform.bindings.join('\n')}
${body}
${exported.map((name) => `\t\texports.${name} = ${name};`).join('\n')}
		return module.exports;
	},
});
`;

await mkdir(path.dirname(outPath), { recursive: true });
await writeFile(outPath, bundle, 'utf8');
process.stdout.write(`built ${path.relative(root, outPath)} (${Buffer.byteLength(bundle)} bytes)\n`);
